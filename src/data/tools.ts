export function getToolBySlug(slug: string): ToolMetadata | undefined {
  return TOOLS.find((tool) => tool.slug === slug);
}

export function getToolsByCategory(category: string): ToolMetadata[] {
  return TOOLS.filter((tool) => tool.category === category);
}

export function getPopularTools(): ToolMetadata[] {
  return TOOLS.filter(
    (tool) => tool.status === 'active' && (tool.badge === 'Popular' || tool.badge === 'High Intent' || tool.badge === 'Student Favorite')
  ).slice(0, 8);
}
